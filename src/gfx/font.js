/** Pixel width of a string at scale 1 (glyphs + tracking, no trailing gap). */
export function measureText(text) {
  if (text.length === 0) return 0;
  return text.length * GLYPH_W + (text.length - 1) * TRACKING;
}

/**
 * The lit pixels of a string as [{x, y}] offsets from the text's top-left.
 * Case-insensitive; characters without a glyph render as space.
 */
export function textPixels(text) {
  const out = [];
  let cx = 0;
  for (const raw of text.toUpperCase()) {
    const glyph = GLYPHS[raw] ?? GLYPHS[' '];
    for (let y = 0; y < GLYPH_H; y++) {
      const row = glyph[y];
      for (let x = 0; x < GLYPH_W; x++) {
        if (row[x] === '1') out.push({ x: cx + x, y });
      }
    }
    cx += GLYPH_W + TRACKING;
  }
  return out;
}
